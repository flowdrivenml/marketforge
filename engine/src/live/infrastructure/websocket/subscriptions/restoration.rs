// ============================================================
// ERRORS
// ============================================================

#[derive(Debug, Error)]
pub enum SubscriptionRestorationError {
    #[error("demand revision must be greater than zero")]
    InvalidRevision,

    #[error("invalid stream identifier")]
    InvalidStreamId,

    #[error("invalid channel name")]
    InvalidChannel,

    #[error("invalid native instrument symbol")]
    InvalidSymbol,

    #[error("duplicate desired stream: {0}")]
    DuplicateStream(String),

    #[error("connection generation is not current")]
    StaleConnection,

    #[error("connection has not completed its handshake")]
    ConnectionNotEstablished,

    #[error("demand revision changed")]
    StaleDemand,

    #[error("cannot resolve subscription for stream '{stream_id}': {reason}")]
    Resolution { stream_id: String, reason: String },
}

// ============================================================
// DESIRED SUBSCRIPTION
// ============================================================

/// Description of one currently desired source stream.
///
/// This is a transport-facing projection of authoritative
/// stream-registry demand.
///
/// The native symbol and additional variables must
/// already have been validated by their owning components.
///
/// This object does not imply that a subscription exists
/// on any physical WebSocket connection.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DesiredSubscription {
    pub stream_id: String,
    pub channel_name: String,
    pub native_symbol: String,

    /// Explicit native subscription parameters.
    ///
    /// Examples:
    /// - depth
    /// - interval
    /// - native_ws_inst_type
    ///
    /// Symbol variables are generated by the existing
    /// SubscriptionResolutionContext.
    pub variables: BTreeMap<String, String>,
}

impl DesiredSubscription {
    pub fn new(
        stream_id: impl Into<String>,
        channel_name: impl Into<String>,
        native_symbol: impl Into<String>,
    ) -> Result<Self, SubscriptionRestorationError> {
        let stream_id = stream_id.into();
        let channel_name = channel_name.into();
        let native_symbol = native_symbol.into();

        if !valid_identifier(&stream_id) {
            return Err(SubscriptionRestorationError::InvalidStreamId);
        }

        if !valid_identifier(&channel_name) {
            return Err(SubscriptionRestorationError::InvalidChannel);
        }

        if !valid_identifier(&native_symbol) {
            return Err(SubscriptionRestorationError::InvalidSymbol);
        }

        Ok(Self {
            stream_id,
            channel_name,
            native_symbol,
            variables: BTreeMap::new(),
        })
    }

    pub fn with_variable(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.variables.insert(name.into(), value.into());
        self
    }

    fn resolution_context(
        &self,
    ) -> Result<SubscriptionResolutionContext, SubscriptionResolutionError> {
        let mut context = SubscriptionResolutionContext::new(self.native_symbol.clone())?;

        for (name, value) in &self.variables {
            context = context.with_variable(name.clone(), value.clone())?;
        }

        Ok(context)
    }
}

// ============================================================
// DESIRED DEMAND SNAPSHOT
// ============================================================

/// Immutable projection of current desired stream demand.
///
/// The revision is assigned by the authoritative demand
/// owner. It must increase whenever desired demand changes.
///
/// Revision numbers must never be reused within the
/// owning registry incarnation.
#[derive(Debug, Clone)]
pub struct DesiredSubscriptionSnapshot {
    revision: u64,
    entries: BTreeMap<String, DesiredSubscription>,
}

impl DesiredSubscriptionSnapshot {
    pub fn new(
        revision: u64,
        subscriptions: impl IntoIterator<Item = DesiredSubscription>,
    ) -> Result<Self, SubscriptionRestorationError> {
        if revision == 0 {
            return Err(SubscriptionRestorationError::InvalidRevision);
        }

        let mut entries = BTreeMap::new();

        for subscription in subscriptions {
            let stream_id = subscription.stream_id.clone();

            if entries.insert(stream_id.clone(), subscription).is_some() {
                return Err(SubscriptionRestorationError::DuplicateStream(stream_id));
            }
        }

        Ok(Self { revision, entries })
    }

    pub fn revision(&self) -> u64 {
        self.revision
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn get(&self, stream_id: &str) -> Option<&DesiredSubscription> {
        self.entries.get(stream_id)
    }

    pub fn iter(&self) -> impl Iterator<Item = &DesiredSubscription> {
        self.entries.values()
    }
}

// ============================================================
// RESOLVED RESTORATION ENTRY
// ============================================================

/// One planned subscription for a specific physical
/// connection generation.
///
/// It has not yet been sent to the exchange.
///
/// It does not have a source-stream epoch or ACK authority.
#[derive(Debug)]
pub struct PlannedSubscription {
    pub stream_id: String,
    pub resolved: ResolvedSubscription,
}

// ============================================================
// RESTORATION PLAN
// ============================================================

/// Resolved subscriptions for one connection generation
/// and one immutable desired-demand revision.
///
/// A plan cannot be transferred to another generation.
#[derive(Debug)]
pub struct SubscriptionRestorationPlan {
    stamp: ConnectionStamp,
    demand_revision: u64,
    entries: Vec<PlannedSubscription>,
}

impl SubscriptionRestorationPlan {
    pub fn stamp(&self) -> &ConnectionStamp {
        &self.stamp
    }

    pub fn demand_revision(&self) -> u64 {
        self.demand_revision
    }

    pub fn entries(&self) -> &[PlannedSubscription] {
        &self.entries
    }

    pub fn into_entries(self) -> Vec<PlannedSubscription> {
        self.entries
    }

    /// Preliminary eligibility check before execution.
    ///
    /// `current_demand_revision` must be read from the
    /// authoritative registry, not from this plan.
    ///
    /// This is not an atomic authorization to mutate
    /// stream state. The runtime coordinator must serialize
    /// demand reconciliation with plan execution.
    pub fn is_current(&self, fence: &ConnectionFence, current_demand_revision: u64) -> bool {
        self.demand_revision == current_demand_revision
            && fence.current_stamp().as_ref() == Some(&self.stamp)
            && matches!(
                fence.state(),
                ConnectionState::Connected | ConnectionState::Ready
            )
    }
}

// ============================================================
// RESTORATION PLANNER
// ============================================================

/// Compile one demand snapshot into native subscription
/// requests for a specific physical WebSocket generation.
///
/// No socket I/O.
/// No subscription transmission.
/// No mutation of source-stream epochs.
/// No ownership of consumer demand.
pub struct SubscriptionRestorationPlanner;

impl SubscriptionRestorationPlanner {
    pub fn plan(
        exchange: &ExchangeConfig,
        fence: &ConnectionFence,
        stamp: &ConnectionStamp,
        desired: &DesiredSubscriptionSnapshot,
    ) -> Result<SubscriptionRestorationPlan, SubscriptionRestorationError> {
        // ----------------------------------------------------
        // PHYSICAL CONNECTION AUTHORITY
        // ----------------------------------------------------

        if fence.current_stamp().as_ref() != Some(stamp) {
            return Err(SubscriptionRestorationError::StaleConnection);
        }

        if !matches!(
            fence.state(),
            ConnectionState::Connected | ConnectionState::Ready
        ) {
            return Err(SubscriptionRestorationError::ConnectionNotEstablished);
        }

        // ----------------------------------------------------
        // PREFLIGHT ALL DESIRED SUBSCRIPTIONS
        // ----------------------------------------------------

        let mut entries = Vec::with_capacity(desired.len());

        for subscription in desired.iter() {
            let context = subscription.resolution_context().map_err(|error| {
                SubscriptionRestorationError::Resolution {
                    stream_id: subscription.stream_id.clone(),
                    reason: error.to_string(),
                }
            })?;

            let resolved =
                SubscriptionResolver::resolve(exchange, &subscription.channel_name, &context)
                    .map_err(|error| SubscriptionRestorationError::Resolution {
                        stream_id: subscription.stream_id.clone(),
                        reason: error.to_string(),
                    })?;

            entries.push(PlannedSubscription {
                stream_id: subscription.stream_id.clone(),
                resolved,
            });
        }

        // ----------------------------------------------------
        // NO SIDE EFFECTS
        // ----------------------------------------------------

        // All entries have been successfully resolved.
        //
        // The caller receives either the full plan or
        // an error. No partial subscriptions were sent.
        Ok(SubscriptionRestorationPlan {
            stamp: stamp.clone(),
            demand_revision: desired.revision(),
            entries,
        })
    }
}

// ============================================================
// VALIDATION
// ============================================================

fn valid_identifier(value: &str) -> bool {
    !value.is_empty()
        && value.trim() == value
        && !value
            .chars()
            .any(|character| character.is_whitespace() || character.is_control())
}

